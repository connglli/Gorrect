package io.connglli.gorrect.gir.inst;

import io.connglli.gorrect.gir.GProgramVisitor;
import io.connglli.gorrect.gir.inst.marks.GIRMarkReinterpretable;
import io.connglli.gorrect.gir.model.GGraph;
import lombok.*;
import lombok.experimental.FieldDefaults;

/**
 * GAddAnonymRootInstruction adds a new anonymous root object to the graph. The object does not have
 * a user-defined name and is highly likely that it cannot be referenced later (except that the user
 * knows its internal name). The internal name of the object should be defined based on the
 * instruction index, require that, for GAddAnonymRootInstruction instructions of the same index,
 * the same internal name should be generated by the interpreter. Yet, the interpreter is flexible
 * in defining the format of the internal name, as long as it is unique and consistent.
 */
@RequiredArgsConstructor
@FieldDefaults(makeFinal = true, level = AccessLevel.PRIVATE)
@Getter
@EqualsAndHashCode(callSuper = true)
@GIROpCode("add-anonym-root")
public class GAddAnonymRootInstruction extends GInstruction implements GIRMarkReinterpretable {

  /** The size in bytes of the new anonymous root to be created. */
  @GIRInput(0)
  @NonNull
  Long objectSize;

  @Override
  public <T> T accept(GProgramVisitor<T> visitor) {
    return visitor.visit(this);
  }

  @Override
  public void checkValidity(GGraph graph) {
    if (objectSize < 0) {
      throw new InvalidInputException(
          "Object size must be non-negative, but got "
              + objectSize
              + " (instruction: "
              + this
              + ")");
    }
    super.checkValidity(graph);
  }
}
